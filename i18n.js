/* ── Core ─────────────────────────────────────────────────────────────────── */
window.__lang = localStorage.getItem('lang') || 'ru';

function setLang(lang) {
  window.__lang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang === 'kz' ? 'kk' : 'ru';

  const page = location.pathname.split('/').pop() || 'index.html';
  const maps = [...(SELECTORS._all || []), ...(SELECTORS[page] || [])];
  const t = T[lang];

  maps.forEach(item => {
    if (item.each) {
      const els = document.querySelectorAll(item.sel);
      item.each.forEach((key, i) => {
        if (!els[i] || !t[key]) return;
        applyTranslation(els[i], t[key], item.type || 'html');
      });
    } else {
      const el = document.querySelector(item.sel);
      if (!el || !t[item.key]) return;
      applyTranslation(el, t[item.key], item.type || 'html');
    }
  });

  // Render stages list (about.html special case)
  renderStages(lang);

  // Update lang toggle buttons
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.l === lang);
  });

  // Update page title
  const titles = {
    ru: { 'index.html': 'LogiChain — Аналитика логистических цепочек', 'analytics.html': 'Аналитика — LogiChain', 'ai-tools.html': 'AI-инструменты — LogiChain', 'about.html': 'О проекте — LogiChain', 'contact.html': 'Контакты — LogiChain' },
    kz: { 'index.html': 'LogiChain — Логистикалық тізбектер аналитикасы', 'analytics.html': 'Аналитика — LogiChain', 'ai-tools.html': 'AI-құралдар — LogiChain', 'about.html': 'Жоба туралы — LogiChain', 'contact.html': 'Байланыс — LogiChain' },
  };
  if (titles[lang][page]) document.title = titles[lang][page];
}

function applyTranslation(el, val, type) {
  if (type === 'text') el.textContent = val;
  else if (type === 'html') el.innerHTML = val;
  else if (type === 'ph') el.placeholder = val;
}

function renderStages(lang) {
  const container = document.getElementById('stages-list');
  if (!container) return;
  const stages = T[lang]['ab.stages'];
  if (!stages) return;
  container.innerHTML = stages.map(([date, title, desc], i) => `
    <div style="display:flex;gap:1.25rem;padding:1.1rem 0;border-bottom:1px solid rgba(255,255,255,0.05);">
      <div style="width:32px;height:32px;border-radius:50%;background:var(--grad);display:flex;align-items:center;justify-content:center;font-size:0.8rem;font-weight:700;flex-shrink:0;color:white;">${i+1}</div>
      <div style="flex:1;">
        <div style="display:flex;align-items:center;gap:0.75rem;flex-wrap:wrap;margin-bottom:0.2rem;">
          <span style="font-family:'Space Grotesk',sans-serif;font-size:0.9rem;font-weight:600;">${title}</span>
          <span class="badge badge-ok" style="font-size:0.68rem;">${date}</span>
        </div>
        <p style="font-size:0.82rem;color:var(--text-dim);">${desc}</p>
      </div>
    </div>`).join('');
}

/* ── Init: inject toggle + apply saved lang ──────────────────────────────── */
document.addEventListener('DOMContentLoaded', () => {
  // Inject lang toggle into header
  const header = document.querySelector('header');
  if (header) {
    const toggle = document.createElement('div');
    toggle.className = 'lang-toggle';
    toggle.innerHTML = `
      <button class="lang-btn${window.__lang === 'ru' ? ' active' : ''}" data-l="ru" onclick="setLang('ru')">РУ</button>
      <button class="lang-btn${window.__lang === 'kz' ? ' active' : ''}" data-l="kz" onclick="setLang('kz')">ҚЗ</button>`;
    header.appendChild(toggle);
  }

  // Render stages on page load (about.html)
  renderStages(window.__lang);

  // Apply saved language (skip if Russian, it's the default)
  if (window.__lang === 'kz') setLang('kz');
});
